#!/usr/bin/env node
/**
 * Vendor the site's webfonts into public/fonts/ and write public/fonts.css.
 *
 *   node tools/self-host-fonts.mjs            # fetch and write
 *   node tools/self-host-fonts.mjs --check    # verify what is on disk matches
 *
 * Why this exists. index.html used to load its two families from
 * fonts.googleapis.com (a stylesheet) and fonts.gstatic.com (the files). Both
 * origins had to be named in the Content-Security-Policy — `style-src` for the
 * stylesheet, `font-src` for the files — and that is the whole reason this site's
 * CSP was wider than its siblings': every other host in this collection serves
 * its type from its own directory. Two third-party origins on the critical path
 * bought nothing but a DNS lookup, a TLS handshake and a render-blocking
 * stylesheet before the first paint.
 *
 * So the files live here now, and the policy says `font-src 'self'` like the rest
 * of the family. Re-run this script to update the fonts; it downloads what the
 * Google CSS asks for and rewrites fonts.css against local paths, so the two can
 * never disagree about which files exist.
 *
 * Which subsets: `latin` and `latin-ext` only. Google answers with a subset per
 * script (cyrillic, greek, vietnamese …), each with a `unicode-range` so a browser
 * fetches only the ones the page's text needs. This site's text is English, so
 * the other subsets would be files committed, uploaded and never requested; a
 * glyph outside latin-ext falls back to the system font exactly as an
 * unreachable webfont would have. Add a name to SUBSETS if that ever changes.
 *
 * `--check` is for CI and for a reviewer: it fails when public/fonts.css does not
 * name the files on disk, or a file it names is missing, so a half-applied font
 * change cannot reach a deploy.
 */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const FONT_DIR = join(ROOT, "public", "fonts");
const CSS_PATH = join(ROOT, "public", "fonts.css");

/** The families and weights index.html uses, in the order they were loaded. */
const FAMILIES = [
  { family: "Inter", weights: [400, 600] },
  { family: "Rajdhani", weights: [600, 700] },
];
/** Google's subset names to keep. See the note above. */
const SUBSETS = ["latin", "latin-ext"];
/** A desktop browser user-agent: the woff2 format is only served to one. */
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36";

const query = FAMILIES.map(
  ({ family, weights }) => `family=${family.replace(/ /g, "+")}:wght@${weights.join(";")}`
).join("&");

/** [ { subset, family, weight, url } ] for the blocks we keep. */
function parseCss(css) {
  const faces = [];
  // Each block is preceded by a `/* subset */` comment; the block itself carries
  // the family, weight and file URL. Splitting on the comment keeps the two
  // together without a CSS parser for 20 known-shape blocks.
  const blocks = css.split(/\/\*\s*([a-z-]+)\s*\*\//i);
  for (let i = 1; i < blocks.length; i += 2) {
    const subset = blocks[i].trim();
    const block = blocks[i + 1] || "";
    if (!SUBSETS.includes(subset)) continue;
    const family = /font-family:\s*'([^']+)'/.exec(block);
    const weight = /font-weight:\s*(\d+)/.exec(block);
    const url = /url\((https:\/\/[^)]+\.woff2)\)/.exec(block);
    if (!family || !weight || !url) continue;
    faces.push({ subset, family: family[1], weight: Number(weight[1]), url: url[1] });
  }
  return faces;
}

const fileFor = (face) => `${face.family.toLowerCase()}-${face.weight}-${face.subset}.woff2`;

function cssFor(faces) {
  const lines = [
    "/* GENERATED by tools/self-host-fonts.mjs — do not hand-edit.",
    " *",
    " * The site's webfonts, served from /fonts/ rather than from Google, which is",
    " * what lets the CSP say `font-src 'self'` and `style-src 'self'` with no third",
    " * party in either (see the Content-Security-Policy in _headers). Re-run the",
    " * script to update; it rewrites this file from the same fetch that downloads",
    " * the files, so the two cannot drift.",
    " *",
    " * latin and latin-ext only: the subsets the site's own text needs. `font-display:",
    " * swap` is kept from Google's CSS so text paints immediately in the fallback",
    " * face rather than waiting on a font.",
    " */",
  ];
  for (const face of faces) {
    lines.push(
      "@font-face {",
      `  font-family: '${face.family}';`,
      "  font-style: normal;",
      `  font-weight: ${face.weight};`,
      "  font-display: swap;",
      `  src: url('/fonts/${fileFor(face)}') format('woff2');`,
      "}"
    );
  }
  return lines.join("\n") + "\n";
}

const checkOnly = process.argv.includes("--check");

if (checkOnly) {
  if (!existsSync(CSS_PATH)) {
    console.error("self-host-fonts: public/fonts.css is missing — run node tools/self-host-fonts.mjs");
    process.exit(1);
  }
  const css = await readFile(CSS_PATH, "utf8");
  const named = [...css.matchAll(/url\('\/fonts\/([^']+)'\)/g)].map((m) => m[1]);
  const onDisk = existsSync(FONT_DIR) ? await readdir(FONT_DIR) : [];
  const missing = named.filter((name) => !onDisk.includes(name));
  const extra = onDisk.filter((name) => !named.includes(name));
  if (missing.length || extra.length) {
    if (missing.length) console.error(`self-host-fonts: fonts.css names files that are not on disk: ${missing.join(", ")}`);
    if (extra.length) console.error(`self-host-fonts: files on disk that fonts.css does not name: ${extra.join(", ")}`);
    console.error("  re-run: node tools/self-host-fonts.mjs");
    process.exit(1);
  }
  console.log(`OK: ${named.length} self-hosted font file(s) named by fonts.css and present in public/fonts/`);
  process.exit(0);
}

const res = await fetch(
  `https://fonts.googleapis.com/css2?${query}&display=swap`,
  { headers: { "user-agent": UA } }
);
if (!res.ok) {
  console.error(`self-host-fonts: Google's CSS answered HTTP ${res.status}`);
  process.exit(2);
}
const faces = parseCss(await res.text());
if (faces.length !== FAMILIES.reduce((n, f) => n + f.weights.length, 0) * SUBSETS.length) {
  console.error(
    `self-host-fonts: expected ${FAMILIES.reduce((n, f) => n + f.weights.length, 0) * SUBSETS.length} face(s) for ${SUBSETS.join("+")}, parsed ${faces.length} — Google's CSS shape may have changed`
  );
  process.exit(2);
}

await mkdir(FONT_DIR, { recursive: true });
let bytes = 0;
for (const face of faces) {
  const file = fileFor(face);
  const fileRes = await fetch(face.url, { headers: { "user-agent": UA } });
  if (!fileRes.ok) {
    console.error(`self-host-fonts: ${face.url} answered HTTP ${fileRes.status}`);
    process.exit(2);
  }
  const body = Buffer.from(await fileRes.arrayBuffer());
  if (body.subarray(0, 4).toString("latin1") !== "wOF2") {
    console.error(`self-host-fonts: ${face.url} did not return a woff2 file`);
    process.exit(2);
  }
  await writeFile(join(FONT_DIR, file), body);
  bytes += body.length;
  console.log(`  ${file}  ${(body.length / 1024).toFixed(1)} KB  (${face.subset})`);
}
await writeFile(CSS_PATH, cssFor(faces), "utf8");
console.log(`self-host-fonts: ${faces.length} file(s), ${(bytes / 1024).toFixed(1)} KB -> public/fonts/, and public/fonts.css rewritten`);
